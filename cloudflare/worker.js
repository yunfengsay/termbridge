function relayTopology(input) {
  const name = (text) => text.replace(/[\u0000-\u001f\u007f]/g, " ").slice(0, 96);
  const grouped = /* @__PURE__ */ new Map();
  for (const peer of input.peers) {
    const previous = grouped.get(peer.id);
    if (previous) previous.connections = Math.min(previous.connections + 1, 1e6);
    else grouped.set(peer.id, { ...peer, name: name(peer.name), connections: 1 });
  }
  const priority = (node) => node.id === input.selfNodeId ? 0 : node.role === "host" && node.hostId === input.selectedHostId ? 1 : node.role === "host" ? 2 : 3;
  const peers = [...grouped.values()].sort((a, b) => priority(a) - priority(b) || a.id.localeCompare(b.id)).slice(0, 127);
  const nodes = [{ id: input.relayId, role: "relay", name: name(input.relayName), connections: 1 }, ...peers];
  return {
    t: "relay_topology",
    relayId: input.relayId,
    selfNodeId: input.selfNodeId,
    selectedHostId: input.selectedHostId,
    generatedAt: Date.now(),
    nodes,
    edges: peers.map((peer) => ({ from: peer.id, to: input.relayId })),
    truncated: grouped.size > peers.length
  };
}

