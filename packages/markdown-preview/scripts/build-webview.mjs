// Bundle the Tiptap Markdown preview surface into a native shell's Resources folder.
//
// Self-contained — zero CDN, zero network script/style fetches — running inside
// a locked-down WKWebView whose CSP allows only bundled resources and the custom
// `tb-md-asset:` scheme backed by Host `session_file_read`.
import { build } from 'esbuild';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { MARKDOWN_PREVIEW_CSS } from '../src/styles.ts';

const here = dirname(fileURLToPath(import.meta.url));
const packageRoot = join(here, '..');
const repoRoot = join(packageRoot, '..', '..');
const args = process.argv.slice(2);
if (args.includes('--help')) {
  console.log('Usage: pnpm build:markdown-preview [output-directory | --out-dir output-directory]');
  process.exit(0);
}
const output = args[0] === '--out-dir' ? args[1] : args[0];
if ((args[0] === '--out-dir' && (args.length !== 2 || !output)) ||
    (args[0] !== '--out-dir' && (args.length > 1 || args[0]?.startsWith('-')))) {
  throw new Error('Expected one output directory; use --out-dir <directory> or --help.');
}
const target = output
  ? resolve(output)
  : join(repoRoot, 'macos', 'TermBridgeControlCenter', 'Sources', 'TermBridgeControlCenter', 'Resources', 'MarkdownPreview');

mkdirSync(target, { recursive: true });

// Collect exact licences from the installed node_modules bundled into markdown.js.
function readPackageLicense(name, baseDir = join(packageRoot, 'node_modules')) {
  const pkgDir = join(baseDir, name);
  const manifestPath = join(pkgDir, 'package.json');
  if (!existsSync(manifestPath)) throw new Error(`missing installed package ${name} at ${pkgDir}`);
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
  const license = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license', 'license.md']
    .map((file) => {
      const candidate = join(pkgDir, file);
      return existsSync(candidate) ? readFileSync(candidate, 'utf8') : undefined;
    })
    .find((text) => text);
  if (!license) throw new Error(`no licence file shipped with ${name}; cannot bundle it`);
  const extraNotices = existsSync(join(pkgDir, 'THIRD_PARTY_LICENSES.md'))
    ? readFileSync(join(pkgDir, 'THIRD_PARTY_LICENSES.md'), 'utf8')
    : undefined;
  return {
    name,
    version: String(manifest.version ?? 'unknown'),
    spdx: String(manifest.license ?? 'see text'),
    license,
    extraNotices,
  };
}

// Also locate transitive highlight.js inside pnpm's layout for lowlight.
function readTransitiveHighlightJs() {
  const lowlightPkg = join(packageRoot, 'node_modules', 'lowlight');
  const candidates = [
    join(lowlightPkg, 'node_modules', 'highlight.js'),
    join(packageRoot, 'node_modules', 'highlight.js'),
    join(repoRoot, 'node_modules', 'highlight.js'),
  ];
  for (const dir of candidates) {
    if (existsSync(join(dir, 'package.json'))) {
      return readPackageLicense('highlight.js', dirname(dir));
    }
  }
  return undefined;
}

const directDeps = [
  '@tiptap/core',
  '@tiptap/pm',
  '@tiptap/starter-kit',
  '@tiptap/extension-image',
  '@tiptap/extension-table',
  '@tiptap/extension-task-list',
  '@tiptap/extension-task-item',
  '@tiptap/extension-code-block-lowlight',
  'lowlight',
  'marked',
];
const bundled = directDeps.map((name) => readPackageLicense(name));
const hljs = readTransitiveHighlightJs();
if (hljs) bundled.push(hljs);

const licenseNotice = [
  '# Third-party licences bundled into markdown.js',
  '',
  'Generated by `packages/markdown-preview/scripts/build-webview.mjs` from the',
  'installed packages, so it names the exact versions in this `markdown.js`.',
  '',
  ...bundled.flatMap(({ name, version, spdx, license, extraNotices }) => [
    `## ${name} ${version}`,
    '',
    `SPDX: ${spdx}`,
    '',
    '```',
    license.trimEnd(),
    '```',
    '',
    ...(extraNotices ? [extraNotices.trimEnd(), ''] : []),
  ]),
].join('\n');

const banner = `/*! Bundles ${bundled.map((d) => `${d.name} ${d.version} (${d.spdx})`).join(', ')};`
  + ' full licence text in THIRD_PARTY_LICENSES.md, shipped alongside this file. */';

await build({
  entryPoints: [join(packageRoot, 'src', 'webview.ts')],
  outfile: join(target, 'markdown.js'),
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['safari15'],
  minify: true,
  legalComments: 'inline',
  banner: { js: banner },
  absWorkingDir: repoRoot,
  logLevel: 'info',
});

writeFileSync(join(target, 'THIRD_PARTY_LICENSES.md'), licenseNotice);
writeFileSync(join(target, 'markdown.css'), MARKDOWN_PREVIEW_CSS.trimStart());
writeFileSync(join(target, 'index.html'), [
  '<!doctype html><html><head><meta charset="utf-8">',
  '<meta name="viewport" content="width=device-width, initial-scale=1">',
  // Self-contained bundle; local/remote Host images arrive via our custom WKURLSchemeHandler (`tb-md-asset:`).
  '<meta http-equiv="Content-Security-Policy" content="default-src \'self\'; script-src \'self\'; style-src \'self\'; img-src \'self\' tb-md-asset: https: data:; connect-src \'none\'; object-src \'none\'">',
  '<link rel="stylesheet" href="markdown.css">',
  '</head><body><div id="markdown-scroll"><div id="markdown-root"></div></div><script src="markdown.js"></script></body></html>',
].join(''));

console.log(`[markdown-preview] wrote markdown.js, markdown.css, index.html and THIRD_PARTY_LICENSES.md to ${target}`);
