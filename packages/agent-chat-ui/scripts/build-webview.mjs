// Bundle the shared conversation surface into a native shell's web folder.
//
// Windows, macOS and the phones consume the same three files. The output is self-contained — no CDN,
// no network — because it runs inside a WebView with a locked-down CSP.
import { build } from 'esbuild';
import { createRequire } from 'node:module';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { TRANSCRIPT_CSS } from '../src/styles.ts';

const here = dirname(fileURLToPath(import.meta.url));
const packageRoot = join(here, '..');
const repoRoot = join(packageRoot, '..', '..');
const args = process.argv.slice(2);
if (args.includes('--help')) {
  console.log('Usage: pnpm build:agent-chat-ui [output-directory | --out-dir output-directory]');
  process.exit(0);
}
const output = args[0] === '--out-dir' ? args[1] : args[0];
if ((args[0] === '--out-dir' && (args.length !== 2 || !output)) ||
    (args[0] !== '--out-dir' && (args.length > 1 || args[0]?.startsWith('-')))) {
  throw new Error('Expected one output directory; use --out-dir <directory> or --help.');
}
const target = output ? resolve(output) : join(repoRoot, 'windows', 'TermBridge.App', 'Chat');

mkdirSync(target, { recursive: true });

// Third-party code ends up inside `chat.js`, so its licence has to travel with
// the shell that ships it. Read from the installed package rather than a copy
// kept here, so the text can never drift from the version actually bundled.
const require = createRequire(import.meta.url);
const bundled = ['marked'].map((name) => {
  const manifest = require(`${name}/package.json`);
  const root = dirname(require.resolve(`${name}/package.json`));
  const license = ['LICENSE', 'LICENSE.md', 'LICENSE.txt']
    .map((file) => {
      try { return readFileSync(join(root, file), 'utf8'); } catch { return undefined; }
    })
    .find((text) => text);
  if (!license) throw new Error(`no licence file shipped with ${name}; cannot bundle it`);
  return { name, version: manifest.version, spdx: manifest.license ?? 'see text', license };
});

const licenseNotice = [
  '# Third-party licences bundled into chat.js',
  '',
  'Generated by `packages/agent-chat-ui/scripts/build-webview.mjs` from the',
  'installed packages, so it names the exact versions in this `chat.js`.',
  '',
  ...bundled.flatMap(({ name, version, spdx, license }) => [
    `## ${name} ${version}`,
    '',
    `SPDX: ${spdx}`,
    '',
    '```',
    license.trimEnd(),
    '```',
    '',
  ]),
].join('\n');

// A reader who has only the bundle still learns what is in it and where the
// full text sits. Kept to one line so the minified output stays diffable.
const banner = `/*! Bundles ${bundled.map((d) => `${d.name} ${d.version} (${d.spdx})`).join(', ')};`
  + ' full licence text in THIRD_PARTY_LICENSES.md, shipped alongside this file. */';

await build({
  entryPoints: [join(packageRoot, 'src', 'webview.ts')],
  outfile: join(target, 'chat.js'),
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['chrome110', 'safari15'],
  minify: true,
  legalComments: 'inline',
  banner: { js: banner },
  absWorkingDir: repoRoot,
  logLevel: 'info',
});

writeFileSync(join(target, 'THIRD_PARTY_LICENSES.md'), licenseNotice);

writeFileSync(join(target, 'chat.css'), TRANSCRIPT_CSS.trimStart());
writeFileSync(join(target, 'index.html'), [
  '<!doctype html><html><head><meta charset="utf-8">',
  '<meta name="viewport" content="width=device-width, initial-scale=1">',
  // Nothing loads from the network and nothing is evaluated from a string.
  '<meta http-equiv="Content-Security-Policy" content="default-src \'self\'; script-src \'self\'; style-src \'self\'; img-src \'self\' https: data:; connect-src \'none\'; object-src \'none\'">',
  '<link rel="stylesheet" href="chat.css">',
  '</head><body><div id="chat" class="tb-scroll"></div><script src="chat.js"></script></body></html>',
].join(''));

console.log(`[agent-chat-ui] wrote chat.js, chat.css, index.html and THIRD_PARTY_LICENSES.md to ${target}`);
